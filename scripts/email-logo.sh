# Renders the email title ("Santa's Call") with the web font (Mountains of Christmas 700) to a PNG and
# writes it as base64 to amplify/shared/email-logo.ts. Email clients ignore web fonts, so the email
# shows this image instead. Needs Google Chrome. Run again if the title or the colours change.
set -euo pipefail
cd "$(dirname "$0")/.."
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
cp node_modules/@fontsource/mountains-of-christmas/files/mountains-of-christmas-latin-700-normal.woff2 "$tmp/moc.woff2"
render() { # $1 = title, $2 = output png, $3 = width in CSS px
  cat > "$tmp/logo.html" <<HTML
<!doctype html><html><head><style>
@font-face{font-family:'MoC';src:url(moc.woff2) format('woff2');font-weight:700}
html,body{margin:0;background:transparent}
div{display:inline-block;padding:4px 14px 10px 8px;font-family:'MoC';font-weight:700;font-size:80px;line-height:1.1;color:#c8372d;white-space:nowrap;
text-shadow:6px 6px 0 #fff8ec,10px 10px 0 #e8d6b8}
</style></head><body><div>$1</div></body></html>
HTML
  "$chrome" --headless --disable-gpu --hide-scrollbars --default-background-color=00000000 \
    --force-device-scale-factor=2 --virtual-time-budget=3000 --window-size="$3",102 \
    --screenshot="$2" "file://$tmp/logo.html" 2>/dev/null
}
chrome="${CHROME:-/Applications/Google Chrome.app/Contents/MacOS/Google Chrome}"
render "Santa&#39;s Call" "$tmp/logo.png" 400
{
  echo '// Copyright Amazon.com, Inc. or its affiliates. All Rights Reserved.'
  echo '// SPDX-License-Identifier: MIT-0'
  echo '// Generated by scripts/email-logo.sh. Do not edit by hand.'
  echo '// The email title in the web font, as a PNG (2x, shown at 62 px high).'
  printf "export const LOGO_PNG_BASE64 =\n  '%s';\n" "$(base64 < "$tmp/logo.png" | tr -d '\n')"
} > amplify/shared/email-logo.ts
echo "wrote amplify/shared/email-logo.ts"
